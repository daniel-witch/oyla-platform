# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

# Defaults to local SQLite (same as before) - this is what runs both
# locally and on the free Render deployment out of the box, so
# 'dj_database_url'/'psycopg2' are NOT in requirements.txt and don't need
# installing. Only if you later attach a Postgres database (see README.md
# "Cloud deployment") does DATABASE_URL get set - at that point, also add
# `dj-database-url` and `psycopg2-binary` to requirements.txt (and
# reinstall) before deploying, or this will raise ImportError on purpose
# rather than silently falling back to SQLite in production.
_database_url = os.environ.get('DATABASE_URL')
if _database_url:
    import dj_database_url
    DATABASES = {
        'default': dj_database_url.parse(_database_url, conn_max_age=600)
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }


